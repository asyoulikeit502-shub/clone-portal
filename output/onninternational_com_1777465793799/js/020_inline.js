$('.outerwear-collection .home-product_wrapper').hide();
$('.outerwear-image1').on('mouseenter click', function() {
  $('#productLink1').attr('href', '#');
  $('#productImage1').attr('src', '');
  $('#productName1').text('');
  $('#productPrice1').text('');
  const link = $(this).data('link');
  const img = $(this).data('img');
  const name = $(this).data('name');
  const price = $(this).data('price');
  $('.outerwear-collection .home-product_wrapper').css('display', 'flex');
  $('.outerwear-image1').removeClass('active');
  $(this).addClass('active');
  $('#productLink1').attr('href', link);
  $('#productImage1').attr('src', img);
  $('#productName1').text(name);
  $('#productPrice1').text(price);
  $('.product-card').fadeIn(200);
});
